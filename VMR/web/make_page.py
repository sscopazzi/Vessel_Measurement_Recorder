"""Builds the dashboard into VMR.ino: gzips web/index.html and web/logo.svg and writes them as byte
arrays between the PAGE markers at the end of the sketch. Edit the files in web/, then run
    python3 web/make_page.py          (from the sketch folder)
and compile. The VMR sends the arrays as they are, with Content-Encoding: gzip."""
import gzip, os, sys

here = os.path.dirname(os.path.abspath(__file__))
sketch = os.path.join(here, "..", "VMR.ino")
BEGIN = "// ---- PAGE BEGIN (generated by web/make_page.py from web/index.html and web/logo.svg - edit those, then run it) ----"
END = "// ---- PAGE END ----"

def arr(name, data):
    z = gzip.compress(data, compresslevel=9, mtime=0)      # mtime 0: the same input gives the same bytes
    rows = [", ".join("0x%02x" % b for b in z[i:i + 24]) for i in range(0, len(z), 24)]
    return z, "const uint8_t %s[] PROGMEM = {   // %d bytes, gzip of %d\n  %s\n};\nconst size_t %s_LEN = sizeof(%s);\n" % (
        name, len(z), len(data), ",\n  ".join(rows), name, name)

html = open(os.path.join(here, "index.html"), "rb").read()
svg = open(os.path.join(here, "logo.svg"), "rb").read()
zh, a1 = arr("INDEX_HTML_GZ", html)
zs, a2 = arr("LOGO_SVG_GZ", svg)
s = open(sketch, encoding="utf-8").read()
i, j = s.find(BEGIN), s.find(END)
if i < 0 or j < 0:
    sys.exit("PAGE markers not found in VMR.ino")
s = s[:i] + BEGIN + "\n" + a1 + "\n// Aspect Wave LLC logo (currentColor, so the page sets its colour per theme)\n" + a2 + s[j:]
open(sketch, "w", encoding="utf-8").write(s)
print("page %d -> %d bytes, logo %d -> %d bytes" % (len(html), len(zh), len(svg), len(zs)))
