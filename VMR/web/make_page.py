"""Builds the dashboard into VMR.ino: minifies web/index.html's script and style, compresses it and web/logo.svg
with zopfli (gzip format, smaller than gzip -9) and writes them as byte arrays between the PAGE markers at the
end of the sketch. Edit the files in web/, then run
    python3 web/make_page.py          (from the sketch folder)
and compile. The VMR sends the arrays as they are, with Content-Encoding: gzip.

Needs   pip install rjsmin rcssmin zopfli
rjsmin and rcssmin only take out comments and spaces; the script is otherwise left as written. Leaflet, for the
Chart card without internet, is not here: it goes inside each chart pack (charts/make_vmrchart.py)."""
import os, re, sys

try:
    import rjsmin, rcssmin, zopfli.gzip
except ImportError:
    sys.exit("make_page.py needs rjsmin, rcssmin and zopfli:  pip install rjsmin rcssmin zopfli")

here = os.path.dirname(os.path.abspath(__file__))
sketch = os.path.join(here, "..", "VMR.ino")
BEGIN = "// ---- PAGE BEGIN (generated by web/make_page.py from web/index.html and web/logo.svg - edit those, then run it) ----"
END = "// ---- PAGE END ----"


def minify(html):
    """The page with each <script> and <style> block's comments and spaces taken out (the markup as it is)."""
    def js(m): return m.group(1) + rjsmin.jsmin(m.group(2)) + m.group(3)
    def css(m): return m.group(1) + rcssmin.cssmin(m.group(2)) + m.group(3)
    html = re.sub(r"(<script>)(.*?)(</script>)", js, html, flags=re.S)
    return re.sub(r"(<style>)(.*?)(</style>)", css, html, flags=re.S)


def arr(name, data):
    z = zopfli.gzip.compress(data)                          # no file time in the header: the same input gives the same bytes
    rows = [", ".join("0x%02x" % b for b in z[i:i + 24]) for i in range(0, len(z), 24)]
    return z, "const uint8_t %s[] PROGMEM = {   // %d bytes, gzip of %d\n  %s\n};\nconst size_t %s_LEN = sizeof(%s);\n" % (
        name, len(z), len(data), ",\n  ".join(rows), name, name)


if __name__ == "__main__":
    src = open(os.path.join(here, "index.html"), encoding="utf-8").read()
    html = minify(src).encode()
    svg = open(os.path.join(here, "logo.svg"), "rb").read()
    zh, a1 = arr("INDEX_HTML_GZ", html)
    zs, a2 = arr("LOGO_SVG_GZ", svg)
    s = open(sketch, encoding="utf-8").read()
    i, j = s.find(BEGIN), s.find(END)
    if i < 0 or j < 0:
        sys.exit("PAGE markers not found in VMR.ino")
    s = s[:i] + BEGIN + "\n" + a1 + "\n// Aspect Wave LLC logo (currentColor, so the page sets its colour per theme)\n" + a2 + s[j:]
    open(sketch, "w", encoding="utf-8").write(s)
    print("page %d -> %d minified -> %d bytes, logo %d -> %d bytes" % (len(src.encode()), len(html), len(zh), len(svg), len(zs)))
